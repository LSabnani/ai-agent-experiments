class ReportExporter:
    """Generates formatted Text, HTML Print, and PDF evaluation reports for student submissions."""

    @staticmethod
    def generate_text_report(submission: SubmissionRecord) -> str:
        """Builds a comprehensive, readable plain-text report."""
        details: Optional[EvaluationResult] = submission.evaluation_details
        model_name = submission.model_used or (details.model_used if details else "Gemini AI")
        
        lines = []
        lines.append("=" * 80)
        lines.append(f"{'AGENTIC ML SPECIFICATION GRADING REPORT':^80}")
        lines.append("=" * 80)
        lines.append(f"Student Name   : {submission.student_name}")
        lines.append(f"Project Path   : {submission.folder_name}")
        lines.append(f"Submission ID  : {submission.id}")
        lines.append(f"Timestamp (UTC): {submission.timestamp}")
        lines.append(f"AI Model Used  : {model_name}")
        lines.append(f"Overall Score  : {submission.score:.1f}% ({submission.letter_grade})")
        if details:
            lines.append(f"Total Points   : {details.total_score:.1f} / {details.max_possible_score:.1f} pts")
        lines.append("-" * 80)

        if details:
            lines.append(f"\nOVERALL SUMMARY:\n{details.summary}\n")

            if details.strengths:
                lines.append("KEY STRENGTHS:")
                for s in details.strengths:
                    lines.append(f"  ✓ {s}")
                lines.append("")

            if details.deductions:
                lines.append("DEDUCTIONS & AREAS FOR IMPROVEMENT:")
                for d in details.deductions:
                    lines.append(f"  ⚠ {d}")
                lines.append("")

            lines.append("=" * 80)
            lines.append("DETAILED SPECIFICATION CRITERIA BREAKDOWN:")
            lines.append("=" * 80)
            
            for c in details.criteria:
                status_symbol = "[✓ PASS]" if c.status == "PASS" else ("[⚠ PARTIAL]" if c.status == "PARTIAL" else "[✗ FAIL]")
                lines.append(f"\n{status_symbol} {c.title} ({c.earned_score:.1f}/{c.max_score:.1f} pts)")
                lines.append(f"  Category   : {c.category}")
                lines.append(f"  Description: {c.description}")
                lines.append(f"  Findings   : {c.feedback}")
                if c.evidence:
                    lines.append(f"  Evidence   : {c.evidence}")
                if c.earned_score < c.max_score:
                    if c.deduction_reason:
                        lines.append(f"  ⚠️ Deduction: {c.deduction_reason}")
                    if c.fix_recommendation:
                        lines.append(f"  💡 How to Fix: {c.fix_recommendation}")
                lines.append("-" * 40)

        lines.append("\n" + "=" * 80)
        lines.append("End of Evaluation Report - Generated by AutoGrader Pro")
        lines.append("=" * 80 + "\n")
        return "\n".join(lines)

